def save(path: Path, data: dict[str, str]) -> None:
  ordered = dict(sorted(data.items(), key=lambda kv: kv[0]))
  path.write_text(
    json.dumps(ordered, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
  )


def apply_lang(code: str, values: list[str], en: dict[str, str]) -> int:
  if len(values) != len(KEYS):
    raise SystemExit(f"{code}: expected {len(KEYS)} strings, got {len(values)}")
  path = ROOT / f"{code}.json"
  data = json.loads(path.read_text(encoding="utf-8"))
  added = 0
  for key, value in zip(KEYS, values):
    current = data.get(key)
    if current is None or current in ("", key, en.get(key)):
      data[key] = value
      added += 1
  save(path, data)
  return added


def main() -> int:
  en = json.loads((ROOT / "en.json").read_text(encoding="utf-8"))
  en_vals = [en[k] for k in KEYS]
  for code, values in T.items():
    for key, src, dst in zip(KEYS, en_vals, values):
      if tokens(src) != tokens(dst):
        raise SystemExit(f"{code} {key}: format mismatch {tokens(src)} vs {tokens(dst)}")
    n = apply_lang(code, values, en)
    print(f"{code}: wrote {n} keys")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
